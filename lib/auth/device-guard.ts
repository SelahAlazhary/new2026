import "server-only";
import { readDeviceId } from "@/lib/auth/device";
import type { User } from "@/lib/utils/types";

/**
 * فحصُ الجهاز في كلّ طلب — لا عند الدخول وحدَه.
 * ------------------------------------------------------------------
 * **الثغرة التي يسدّها:** كان ربطُ الجهاز يُفحص في `/api/auth/login` فقط.
 * ورمزُ الجلسة بعده مستقلٌّ بنفسه — توقيعُ HMAC وتاريخُ إصدار، لا أكثر.
 * فمن نسخ قيمةَ كوكي الجلسة أعطاها عشرةً من أصحابه، وعملت عندهم جميعاً
 * على أجهزتهم حتى تنتهي صلاحيتُها. والقفلُ الذي في شاشة الدخول يُلتَفّ
 * عليه بلا دخولٍ أصلاً.
 *
 * فصار الجهازُ يُقارَن في كلّ تحميلٍ لصفحةٍ محميّة: كوكي الجهاز في الطلب
 * يجب أن يطابق `deviceId` المخزَّنَ في حساب صاحبه.
 *
 * **وحدُّ ما يفعله — قُلْه صريحاً:** من نسخ **الكوكيين معاً** يمرّ. وهذا
 * قيدُ مصادقةِ الكوكي نفسِها لا عيبُ هذه الدالّة؛ لا يُسدّ إلّا بتوقيعٍ
 * على الجهاز نفسِه. لكنّ الفرقَ عمليٌّ كبير: نسخُ سطرٍ من أدوات المطوّر
 * يفعله كثيرون، ونسخُ كوكيين وزرعُهما بالترتيب الصحيح يفعله قليلون —
 * ومتى أعاد الأستاذُ ضبطَ الجهاز بطلت النسخُ كلُّها دفعةً واحدة.
 *
 * ولا يُنشئ معرّفَ جهازٍ إن لم يكن: `readDeviceId` تقرأ ولا تكتب.
 * والإنشاءُ هنا يعني أن نمنح الزائرَ هويّةً ثمّ نقارنها بنفسها — فتمرّ
 * كلُّ نسخةٍ في أوّل طلب.
 */
export async function deviceMatches(user: User | null | undefined): Promise<boolean> {
  if (!user) return false;

  /*
    صمّامُ الأمان نفسُه الذي في شاشة الدخول: `ADMIN_DEVICE_LOCK=0` يرفع
    القفلَ عن المشرفين وحدهم، لاستعادة الدخول إن فُقد جهاز المالك.
    والطالبُ لا يُستثنى بحال.
  */
  if (user.role === "admin" && process.env.ADMIN_DEVICE_LOCK === "0") return true;

  /* حسابٌ لم يُربَط بجهازٍ بعد يمرّ — الربطُ يقع في أوّل دخول. */
  if (!user.deviceId) return true;

  const device = await readDeviceId();
  return device === user.deviceId;
}
