/**
 * عمقُ الرسوم — ثلاثيّةُ الأبعاد بلا إعادة رسم.
 * ------------------------------------------------------------------
 * الرسومُ مسطّحةٌ بطبعها: مساحاتٌ ملوّنةٌ بحدودٍ سوداء. وإعطاؤها بُعداً
 * ثالثاً لا يلزم منه رسمُها من جديد — يلزم شيئان يفعلهما المتصفّح:
 *
 * **١ ــ البَثق (extrusion).** `drop-shadow` يتبع شكلَ الرسم لا صندوقَه —
 * فيُلقي ظلّاً على حدوده هو. وهي تتراكب: كلُّ ظلٍّ يُلقى على نتيجةِ ما
 * قبله. فعشرةُ ظلالٍ صلبةٍ إزاحةُ كلٍّ بكسلٌ واحدٌ تُنتج جانباً متّصلاً
 * بطول عشرة — وهو الجانبُ المبثوق الذي يجعل الشكلَ جسماً لا صورة.
 *
 * **٢ ــ الإضاءة.** جسمٌ بلا ضوءٍ يبقى مسطّحاً وإن بُثق. فطبقةٌ مقنَّعةٌ
 * بالرسم نفسِه تحمل تدرّجاً من فاتحٍ أعلى إلى غامقٍ أسفل، بمزجٍ `overlay`
 * — فتُضيء أعلاه وتُظلم أسفلَه على منحنياته هو، لا على مستطيلٍ حوله.
 *
 * ولا يُولَّد ملفٌّ لكلّ درجة: أربعُ درجاتٍ × تسعةَ عشرَ رسماً = ستّةٌ
 * وسبعون ملفّاً تتكاثر ولا تُحذف، وتبديلُ الدرجة ينتظر بناءً جديداً.
 * والحسابُ في المتصفّح يجعلها تتبدّل بضغطة.
 *
 * **والظلُّ من لون الهوية لا أسودَ خالصاً.** الأسودُ الخالصُ يُوسّخ الورقَ
 * الدافئ ويبدو دخيلاً عليه؛ والكحليُّ المخفَّفُ يُظلم ولا يشذّ.
 */

export type ArtDepth = "flat" | "soft" | "raised" | "deep";

export const ART_DEPTHS: { id: ArtDepth; name: string; hint: string }[] = [
  { id: "flat", name: "مسطّحة", hint: "كما هي — بلا عمق" },
  { id: "soft", name: "ظلٌّ خفيف", hint: "ترتفع قليلاً عن السطح" },
  { id: "raised", name: "بارزة", hint: "جانبٌ مبثوقٌ قصير — جسمٌ لا صورة" },
  { id: "deep", name: "مجسَّمة", hint: "بَثقٌ طويلٌ وظلٌّ ممتدّ — أقصى ما يكون" },
];

/** ظلٌّ صلبٌ واحد — لبنةُ البَثق. */
const step = (a: number) => `drop-shadow(1px 1px 0 hsl(var(--primary) / ${a}))`;

/** ظلُّ الاستقرار — يُجلس الجسمَ على السطح فلا يبدو طافياً. */
const ground = (y: number, blur: number, a: number) =>
  `drop-shadow(0 ${y}px ${blur}px hsl(var(--primary) / ${a}))`;

/**
 * مرشّحُ العمق — يُضاف بعد مرشّح اللون في السلسلة نفسِها.
 * والترتيبُ مقصود: التلوينُ أوّلاً على البكسل، ثمّ البَثقُ على الناتج —
 * وإلّا بُثق اللونُ الأصليُّ ثمّ لُوِّن الجانبُ معه فاختفى.
 */
export function depthFilter(depth?: string): string {
  switch (depth) {
    case "soft":
      return ground(3, 6, 0.22);
    case "raised":
      /* أربعُ لبناتٍ = جانبٌ بطول أربعة بكسلات */
      return `${step(0.14).repeat(1)}${step(0.14)}${step(0.14)}${step(0.14)} ${ground(5, 9, 0.26)}`;
    case "deep":
      /* تسعُ لبناتٍ، وشدّةُ كلٍّ أخفُّ لئلّا يسودّ الجانبُ بتراكمها */
      return `${Array.from({ length: 9 }, () => step(0.11)).join("")} ${ground(9, 14, 0.3)}`;
    default:
      return "";
  }
}

/** هل تُرسم طبقةُ الإضاءة؟ — لا تُرسم للمسطّحة ولا للظلّ الخفيف. */
export function depthLit(depth?: string): boolean {
  return depth === "raised" || depth === "deep";
}
