export const DEFAULT_AMBIENT: AmbientKind = "off";

/** سرعةُ الحركة — الأبطأُ أهدأ، والدائمُ يُحتمَل بطيئاً لا سريعاً. */
export type AmbientSpeed = "slow" | "normal" | "brisk";

export const AMBIENT_SPEEDS: { id: AmbientSpeed; name: string }[] = [
  { id: "slow", name: "بطيئة" },
  { id: "normal", name: "معتدلة" },
  { id: "brisk", name: "نشِطة" },
];

export function findAmbient(id?: string): Ambient {
  return AMBIENTS.find((x) => x.id === id) ?? AMBIENTS[0];
}

export function ambientClass(x: Ambient, speed?: string): string {
  if (x.id === "off") return "";
  const s = AMBIENT_SPEEDS.some((v) => v.id === speed) ? speed : "normal";
  return `amb amb-${x.id} amb-${s}`;
}
