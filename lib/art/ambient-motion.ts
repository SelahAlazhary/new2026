/**
 * الحركة الدائمة.
 * ------------------------------------------------------------------
 * حركاتُ المنصّة كانت **حركاتِ دخول**: تقع مرّةً حين يظهر العنصر ثمّ
 * تسكن الصفحةُ إلى الأبد. وهذه تُحسّ في الثانية الأولى ولا تُحسّ بعدها.
 *
 * وهذه غيرُها: حركةٌ لا تتوقّف — الألواحُ تتنفّس، والزخرفةُ تدور،
 * والذهبُ يلمع، والخلفيةُ تنساب. تعمل ما دامت الصفحةُ مفتوحة.
 *
 * **وثلاث قواعدَ تحكمها، وإلّا صارت إزعاجاً:**
 *
 * ١ ــ **التفاوت.** لو تحرّك كلُّ لوحٍ في اللحظة نفسِها بدت الصفحةُ
 *      آلةً تخفق. فالتأخيرُ يُشتقّ من ترتيب اللوح (`nth-child`) فيتموّج
 *      المشهدُ ولا يخفق.
 *
 * ٢ ــ **الصغر.** الحركةُ الدائمة تُقاس بالبكسل الواحد لا بالعشرة:
 *      ما يُحسّ ولا يُلاحَظ. وما يُلاحَظ في الثانية الأولى يُتعب في
 *      الدقيقة الخامسة.
 *
 * ٣ ــ **النصُّ لا يتحرّك.** العينُ تتبع الحرف، فحركتُه تمنع القراءة.
 *      تتحرّك الألواحُ والزخارفُ والشاراتُ — لا المتن.
 */

export type AmbientKind =
  | "off"        // ساكنة — كما كانت
  | "breathe"    // تنفّسٌ: تكبيرٌ وتصغيرٌ بالغُ الخفّة
  | "float"      // طفوٌ: ارتفاعٌ وهبوطٌ بطيء
  | "drift"      // انسيابٌ جانبيّ
  | "sway"       // ميلانٌ خفيف
  | "shimmer"    // لمعانٌ يعبر السطح
  | "goldPulse"  // نبضُ الذهب في الحدود والزخارف
  | "aurora"     // خلفيةٌ تنساب ألوانُها
  | "orbit"      // زخارفُ تدور ببطء
  | "ripple"     // تموّجٌ متتابعٌ عبر الألواح
  | "glowPulse"  // هالةٌ تخفت وتشتدّ
  | "living";    // الكلّ معاً — أقصى ما يكون

export type Ambient = {
  id: AmbientKind;
  name: string;
  hint: string;
};

function a(id: AmbientKind, name: string, hint: string): Ambient {
  return { id, name, hint };
}

