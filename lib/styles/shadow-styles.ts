/**
 * ظلالُ العناصر.
 * ------------------------------------------------------------------
 * الظلُّ ليس زخرفةً بل **معلومةُ ارتفاع**: يقول للعين أيُّ لوحٍ أقربُ
 * إليها وأيُّها أبعد. وصفحةٌ بلا ظلٍّ تبدو مطبوعةً على ورق، وصفحةٌ بظلٍّ
 * واحدٍ لكلّ شيءٍ تبدو مقصوصةً بالمقصّ.
 *
 * وثلاثةُ أمورٍ تُميّز الظلَّ الحسن من الغليظ:
 *
 * ١ ــ **طبقتان لا واحدة.** ظلٌّ قريبٌ ضيّقٌ يرسم الحافّة، وظلٌّ بعيدٌ
 *      واسعٌ يعطي الارتفاع. والطبقةُ الواحدة تُنتج هالةً رماديّةً
 *      مسطّحة.
 *
 * ٢ ــ **لونُ الظلّ من لون النصّ لا أسودُ خالص.** الأسودُ يُوسّخ الورقَ
 *      الدافئ ويُطفئ الملوّن؛ ولونُ النصّ يذوب في الهوية.
 *
 * ٣ ــ **الإزاحةُ إلى أسفل وحدَه.** الضوءُ في الواجهات يأتي من أعلى
 *      دائماً، فظلٌّ مائلٌ يمنةً أو يسرةً يناقض بقيّةَ الصفحة.
 */

export type ShadowKind =
  | "none"      // بلا ظلّ — كما هو
  | "hairline"  // خيطٌ تحت الحافّة وحده
  | "soft"      // ناعمٌ منخفض
  | "lifted"    // مرتفعٌ واضح
  | "float"     // طافٍ عالياً
  | "crisp"     // حادٌّ قصير — أقربُ إلى الطباعة
  | "hard"      // صلبٌ مزاحٌ بلا تمويه
  | "inner"     // غائرٌ إلى الداخل
  | "gold"      // مصبوغٌ بالذهب
  | "ink";      // مصبوغٌ بالحبر

export type ShadowStyle = {
  id: ShadowKind;
  name: string;
  hint: string;
};

function s(id: ShadowKind, name: string, hint: string): ShadowStyle {
  return { id, name, hint };
}

export const SHADOW_STYLES: ShadowStyle[] = [
  s("none", "بلا ظلّ", "الألواح مسطّحةٌ على الورق"),
  s("hairline", "الخيط", "خطٌّ رفيعٌ تحت الحافّة وحده"),
  s("soft", "الناعم", "ارتفاعٌ خفيفٌ يُحسّ ولا يُلفت"),
  s("lifted", "المرتفع", "ظلٌّ واضحٌ يرفع اللوح"),
  s("float", "الطافي", "ارتفاعٌ عالٍ وانتشارٌ واسع"),
  s("crisp", "الحادّ", "قصيرٌ قليلُ التمويه — أقربُ للطباعة"),
  s("hard", "الصلب", "مزاحٌ بلا تمويه — نمطُ البروتالِزم"),
  s("inner", "الغائر", "ظلٌّ إلى الداخل يُغوّر اللوح"),
  s("gold", "المذهّب", "مصبوغٌ بلون الذهب"),
  s("ink", "الحِبريّ", "مصبوغٌ بلون الهوية"),
];

export const DEFAULT_SHADOW: ShadowKind = "none";

export function findShadow(id?: string): ShadowStyle {
  return SHADOW_STYLES.find((x) => x.id === id) ?? SHADOW_STYLES[0];
}

export function shadowClass(x: ShadowStyle): string {
  return x.id === "none" ? "" : `sh sh-${x.id}`;
}
