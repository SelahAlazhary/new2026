/**
 * إزالةُ التشكيل — الحركاتُ (الفتحة والضمّة والكسرة والسكون والتنوين
 * والشدّة والمدّة) تُقرأ في المصحف والشعر لا في نصوص الواجهة اليوميّة؛
 * وبعضُ الخطوط العربيّة الحديثة (كاللاليزار المستعمل هنا) تصفّها فوق
 * الحرف بتباعدٍ غيرَ محسوبٍ فتُشوَّه الكلمةُ بصريّاً، فضلاً عن أنّها
 * تجعل الكتابةَ تُقرأ رسميّةً مصطنَعةً لا حديثَ إنسانٍ عاديّ.
 */
export function withoutHarakat(text: string): string {
  return text.replace(/[ؐ-ًؚ-ٰٟۖ-ۭ]/g, "");
}
