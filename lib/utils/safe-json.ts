/**
 * تفليتُ JSON قبل حقنه في وسم `<script>`.
 * ------------------------------------------------------------------
 * **الثغرة:** `JSON.stringify` يُنتج JSON صحيحاً، ولا يُفلّت `<` ولا `>`.
 * فإن حُقن ناتجُه في `<script>` — كما في بياناتِ الفهرسة `ld+json` — كفى
 * أن يحوي أحدُ الحقول `</script>` ليُغلَق الوسمُ باكراً، وما بعده يُقرأ
 * **كودَ صفحةٍ لا نصَّ بيانات**.
 *
 * وحقولُ هذه المنصّة تُكتب من اللوحة: اسمُ الأستاذ، ونبذتُه، وأسماءُ
 * الكورسات والخطط. فمشرفٌ بصلاحية «الكورسات» وحدَها يسمّي كورساً بما
 * يُغلق الوسمَ ويفتح غيرَه — فيعمل ما كتبه في **كلّ صفحةٍ من صفحات
 * الموقع العامّ**، عند كلّ زائر.
 *
 * وكوكي الجلسة `httpOnly` فلا تُقرأ منه؛ لكنّ الكودَ يعمل بصلاحية
 * الزائر: يُرسل طلباتٍ باسمه، ويُبدّل ما يراه، ويطلب كلمةَ مرورٍ في نموذجٍ
 * يشبه نموذجَ المنصّة.
 *
 * **ولا تكفي `Content-Security-Policy`**: سياسةُ هذه المنصّة تُجيز
 * `'unsafe-inline'` في `script-src` — وهو لازمٌ لِما يحقنه Next.js نفسُه
 * من نصوصٍ داخليّة. فالحاجزُ الوحيدُ هو التفليت.
 *
 * **والمفلَّتُ يبقى JSON صحيحاً**: `<` قيمتُها `<` عند أيّ محلّلٍ
 * للـJSON، فتقرؤها محرّكاتُ البحث كما كانت، ولا يراها محلّلُ HTML وسماً.
 *
 * ------------------------------------------------------------------
 * **وفاصلا السطر U+2028 و U+2029 يُفلَّتان معهما.** هما فاصلا أسطرٍ في
 * جافاسكربت ولا يُفلِّتهما `JSON.stringify`، فيكسران النصَّ الداخليّ.
 *
 * وهذا الملفُّ نفسُه وقع فيها أوّلَ ما كُتب: وُضع الحرفان **حرفَين
 * صريحَين** داخل التعبير النمطيّ، فقطعا سطرَ الشيفرة وأبى المترجمُ
 * قراءتَه. فيُكتبان هنا بنقاطهما الشفريّة لا بأنفسهما — وهو
 * الأحوطُ في كلّ حرفٍ غيرِ مرئيّ: ما لا يُرى في المحرّر لا يُراجَع.
 */

const LS = "\u2028";
const PS = "\u2029";

const ESCAPES: Record<string, string> = {
  "<": "\\u003C",
  ">": "\\u003E",
  "&": "\\u0026",
  [LS]: "\\u2028",
  [PS]: "\\u2029",
};

/* التعبيرُ يُبنى من نصٍّ لا من حرفيّةٍ نمطيّة — فلا يقع الحرفُ الكاسرُ في
   الشيفرة أصلاً. */
const RE = new RegExp(`[<>&${LS}${PS}]`, "g");

/** JSON جاهزٌ للحقن داخل `<script>` — لا يُغلق الوسمَ ولا يكسر النصّ. */
export function safeJsonForScript(value: unknown): string {
  return JSON.stringify(value).replace(RE, (c) => ESCAPES[c]);
}
