/**
 * جذرُ اسم المرحلة الإعدادية — يُطابق «إعدادية» و«الثالث الإعدادي».
 */
const PREP_ROOT = "إعداد";

/**
 * هل لهذا الصفّ شُعَب؟
 * ------------------------------------------------------------------
 * الشعبةُ (علمي/أدبي) في الثانوية وحدَها؛ والإعداديُّ صفٌّ واحدٌ لا ينقسم.
 * وكانت لوحةُ الإدارة تعرض قائمةَ الشُّعَب لكلّ صفّ، فيُنشأ كورسٌ «علميّ»
 * لصفٍّ إعداديّ — فيُخفى عن طلابه كلِّهم بلا رسالةِ خطأ: التسجيلُ لا يعطي
 * الإعداديَّ شعبةً أصلاً، فلا يطابق أحدٌ ما ضُبط.
 *
 * والحكمُ من اسم الصفّ لا من حقلٍ ثالثٍ يُضاف: الصفوفُ تُكتب من اللوحة
 * بأسمائها، وحقلٌ جديدٌ يلزم ملءُ كلّ صفٍّ قائمٍ به قبل أن يعمل.
 */
export function gradeHasTrack(grade?: string): boolean {
  return !grade || !grade.includes(PREP_ROOT);
}

/**
 * هل هذا الصفُّ من هذه المرحلة؟
 * ------------------------------------------------------------------
 * كانت شاشةُ التسجيل تعرض الصفوفَ الستّةَ كلَّها مهما اختار الطالبُ
 * مرحلته — فيُسجَّل «ثانوية · الأول الإعدادي · علمي»، وهو تركيبٌ لا وجودَ
 * له. ولا يظهر الخللُ يومَها: يدخل الطالبُ ويرى كورساتٍ، ثمّ تُضبط خطّةٌ
 * لصفّه فتقول اللوحةُ «لا يطابقها أحد» ولا يُفهم لماذا — لأنّ الخطّةَ
 * تُقارَن بمرحلته وهي تخالف صفَّه.
 *
 * والقياسُ بجذر الاسم لا بجدولٍ يُربَط: الصفوفُ تُكتب من اللوحة بأسمائها
 * ولا تحمل مرحلةً، وإضافةُ حقلٍ إليها يلزم ملؤه في كلّ صفٍّ قائم.
 *
 * وما لم يُختر بعدُ لا يُقصي: الحقلُ الفارغ لا يُقارَن.
 */
export function gradeInStage(grade?: string, stage?: string): boolean {
  const g = (grade ?? "").trim();
  const st = (stage ?? "").trim();
  if (!g || !st) return true;
  return g.includes(PREP_ROOT) === st.includes(PREP_ROOT);
}

