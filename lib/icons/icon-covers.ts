export const DEFAULT_ICON_COVER = ICON_COVERS[0].id;

export function findIconCover(id?: string): IconCover {
  return ICON_COVERS.find((x) => x.id === id) ?? ICON_COVERS[0];
}

export function iconCoverClass(x: IconCover): string {
  return x.id === "none" ? "" : `icv-${x.id}`;
}
