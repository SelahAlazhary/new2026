/** مسارُ خانةٍ في هندسةٍ بعينها. */
export function slotPath(lib: IconLib, slot: IconSlot): string {
  if (lib.geo === "solid") return SOLID[slot];
  if (lib.geo === "kufi") return KUFI[slot];
  /* المزدوجةُ تبني من الهندستين معاً، وأساسُها المصمتة. */
  if (lib.geo === "duo") return SOLID[slot];
  return LINE[slot];
}

/** المسارُ الخطّيُّ فوق المساحة — للمزدوجة وحدها. */
export function slotOverlay(lib: IconLib, slot: IconSlot): string | null {
  return lib.geo === "duo" ? LINE[slot] : null;
}

/**
 * سماتُ الرسم.
 * المصمتةُ تُملأ ولا تُخطَّط، والخطّيّةُ تُخطَّط ولا تُملأ — وخلطُهما
 * يُنتج رمزاً ثقيلاً غليظ الحواف.
 */
export function libAttrs(lib: IconLib) {
  const filled = lib.mode === "fill" || lib.mode === "duo";
  return {
    fill: filled ? "currentColor" : "none",
    stroke: lib.mode === "fill" ? "none" : "currentColor",
    strokeWidth: lib.width || undefined,
    strokeLinecap: lib.cap,
    strokeLinejoin: (lib.cap === "butt" ? "miter" : "round") as "miter" | "round",
  };
}

